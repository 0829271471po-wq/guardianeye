def _parse_camera_source(value):
    """แปลงค่า CAMERA_SOURCE จาก .env: ถ้าเป็นตัวเลข (เช่น "0") = webcam, ถ้าไม่ใช่ = ลิงก์ stream"""
    value = (value or "").strip()
    if value == "":
        return 0                  # ไม่ได้ตั้งค่า → ใช้ webcam ตัวแรกของคอม
    if value.isdigit():
        return int(value)         # OpenCV ต้องการเลข int ถึงจะรู้ว่าเป็น webcam
    return value

